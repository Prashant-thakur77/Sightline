#!/usr/bin/env python3
"""YouTube title, description and chapters from the real scene starts in film/film.json; numbers from facts.json.
No credits or attribution lines (the owner adds any credits himself from LICENSES.md / audio/LICENSES.csv).

  python3 video/deliverables.py   -> video/YOUTUBE.md
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
film = json.loads((HERE / "film" / "film.json").read_text())
F = json.loads((HERE / "data" / "facts.json").read_text())
name = film["product"]

starts, t = {}, 0.0
for s in film["scenes"]:
    starts[s["id"]] = t
    t += s["duration"]
total = t

CH = [("open", "A parcel arrives: is this it?"), ("ask", "Shopping by voice, with the Speech Viewer"),
      ("check", "The camera check says what it found"), ("moneyback", "Money back, agent to agent"),
      ("hoodreg", "Under the hood"), ("proof", "Numbers against baselines"), ("recap", "Recap and who does what")]


def mmss(x: float) -> str:
    return f"{int(x // 60)}:{int(x % 60):02d}"


rows, last = [], -99.0
for sid, label in CH:
    st = 0.0 if sid == "open" else starts[sid]
    if st - last >= 10:
        rows.append(f"{mmss(st)} {label}")
        last = st

fa, br, fc, col = F["false_alarms"], F["breaches"], F["false_confirms"], F["colour_caught"]
md = f"""# YouTube and Devpost kit (generated by deliverables.py)

Length: {mmss(total)} ({total:.1f} s). Upload as **Public**, audience "No, it's not made for kids", English, upload
`sightline-film.srt` as English captions. After a few minutes check Studio -> Content -> Restrictions says None.

## Title (under 100 characters)
{name}: blind shoppers pay only after the parcel checks out (PayPal AI Hackathon)

## Description
Blind and low-vision shoppers can buy online, but checking what arrived and getting money back is still left to them.
{name} is a voice-first, screen-reader-first shopping agent: it reads back exactly what you will pay, lets PayPal hold
the money, checks the parcel with your phone camera, and gets the money back from the store's own agent when it is
wrong.

Try it (PayPal sandbox, no sign-up): https://sightline.prashantthakur.dev/judge
Code: https://github.com/Prashant-thakur77/Sightline

Built for the PayPal AI Hackathon with PayPal Orders v2 (authorize), Payments v2 (capture, void, partial capture,
refunds, reauthorization), Vault, JS SDK v6, package tracking, webhooks and Disputes; Claude Opus 5.5 and Claude Haiku
5.5; Channel3 product data; Bryntum Scheduler; AWS.

Numbers in the film come from the repo's eval scripts (evals/RESULTS.md): {fa['k']} of {fa['n']} false alarms on
matching items (CLIP image matching: {fa['baseline_k']} of {fa['baseline_n']}); {br['k']} of {br['n']} payment breaches on
trick listings (naive agent: {br['baseline_k']} of {br['baseline_n']}); colour mismatches caught {col['k']} of {col['n']}
(our weakest result). Built for blind and low-vision shoppers. Maya is a persona; all payments run on the PayPal sandbox.

## Chapters
""" + "\n".join(rows) + """

## Tags
accessibility, blind, low vision, screen reader, PayPal, agentic commerce, Claude, voice shopping, hackathon
"""
(HERE / "YOUTUBE.md").write_text(md)
print(md)
