/**
 * Regenerates evals/RESULTS.md from every evals/results/*.json. Nothing in RESULTS.md is typed by
 * hand: run `pnpm evals:all` (all suites, then this) or `pnpm evals:report` (this only).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVALS_DIR, readResults, scriptPath, type SuiteResult } from './lib/results';

const cell = (s: string | number | undefined) => (s === undefined || s === '' ? '—' : String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '));

function suiteSection(r: SuiteResult): string {
  const out: string[] = [];
  out.push(`## ${r.title}`);
  out.push('');
  out.push(`Suite \`${r.suite}\` · ran ${r.ranAt} · git ${r.gitSha}`);
  out.push('');
  out.push('| Result | Value | Baseline | Interval | n | Script |');
  out.push('| --- | --- | --- | --- | --- | --- |');
  for (const h of r.headlines) {
    const label = h.negative ? `${h.label} **(negative result)**` : h.label;
    out.push(`| ${cell(label)} | ${cell(h.value)} | ${cell(h.baseline)} | ${cell(h.interval)} | ${cell(h.n)} | \`${cell(h.script)}\` |`);
  }
  const notes = r.headlines.filter((h) => h.note);
  if (notes.length > 0) {
    out.push('');
    out.push('Notes:');
    out.push('');
    for (const h of notes) out.push(`- ${h.label}: ${h.note}`);
  }
  if (r.limitations && r.limitations.length > 0) {
    out.push('');
    out.push('Limitations:');
    out.push('');
    for (const l of r.limitations) out.push(`- ${l}`);
  }
  out.push('');
  out.push(`Full per-item data: \`evals/results/${r.suite}.json\` (\`details\`).`);
  return out.join('\n');
}

export function renderReport(results: SuiteResult[]): string {
  const lines: string[] = [];
  lines.push('# Evaluation results');
  lines.push('');
  lines.push(
    `Generated by \`${scriptPath(import.meta.url)}\` from \`evals/results/*.json\`. Every number below was written by the script named next to it. Do not edit this file by hand; run \`pnpm evals:all\`.`,
  );
  lines.push('');
  const liveModel = results.filter((r) => r.suite.endsWith('-live')).map((r) => `\`${r.suite}\``);
  const ledger = sandboxLedgerSuites(results).map((r) => `\`${r.suite}\``);
  const ledgerText = ledger.length
    ? `${ledger.join(' and ')} ran against the PayPal sandbox ledger: real sandbox orders and authorizations (voided afterwards), counted from PayPal's own records.`
    : 'No suite here ran against the PayPal sandbox ledger.';
  const modelText = liveModel.length ? `Only ${liveModel.join(' and ')} called a live model (a small smoke test)` : 'No suite here called a live model.';
  lines.push(
    `Anything simulated says so in its row or its limitations. ${ledgerText} ${
      liveModel.length ? `${modelText}${ledger.length ? '. Every other suite is offline.' : '; every other suite is offline.'}` : modelText
    }`,
  );
  lines.push('');
  if (results.length === 0) {
    lines.push('No result files yet.');
    return `${lines.join('\n')}\n`;
  }
  lines.push('| Suite | Results | Negative results | Ran at (UTC) | Git |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const r of results) {
    lines.push(`| ${cell(r.title)} | ${r.headlines.length} | ${r.headlines.filter((h) => h.negative).length} | ${cell(r.ranAt)} | ${cell(r.gitSha)} |`);
  }
  lines.push('');
  for (const r of results) {
    lines.push(suiteSection(r));
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/**
 * The README's short numbers table: each suite's first result and every negative result, with how it
 * was measured. Written between the README's numbers markers so it can never drift from the files.
 */
/** How a suite was measured, where it is not a plain offline simulation. Kept in step with each suite's own limitations. */
const SANDBOX_HOW = 'sandbox ledger, counted from PayPal sandbox records';

const HOW: Record<string, string> = {
  barrier: 'real store pages, read-only crawl',
  sightbench: 'offline benchmark, synthetic photos',
  'sightbench-looks': 'offline benchmark, synthetic photos',
  'redteam-sandbox': SANDBOX_HOW,
  'duplicates-sandbox': SANDBOX_HOW,
};

/** Suites that ran the real payment path against the PayPal sandbox (written as `<suite>-sandbox`). */
export function isSandboxLedger(r: SuiteResult): boolean {
  return r.suite.endsWith('-sandbox');
}

export function sandboxLedgerSuites(results: SuiteResult[]): SuiteResult[] {
  return results.filter(isSandboxLedger);
}

export function renderReadmeNumbers(results: SuiteResult[]): string {
  const lines: string[] = [];
  const ledger = sandboxLedgerSuites(results).length > 0;
  lines.push(
    `Generated by \`${scriptPath(import.meta.url)}\` from \`evals/results/*.json\`. The last column says how each was measured; ${
      ledger ? 'rows marked "sandbox ledger" were counted from the PayPal sandbox\'s own order and authorization records, and no other row comes from PayPal' : 'none of these numbers comes from the PayPal sandbox ledger'
    }. Full table, intervals and limitations: [evals/RESULTS.md](evals/RESULTS.md).`,
  );
  lines.push('');
  lines.push('| Measure | Result | Baseline | How measured |');
  lines.push('| --- | --- | --- | --- |');
  for (const r of results) {
    const how = HOW[r.suite] ?? (isSandboxLedger(r) ? SANDBOX_HOW : r.suite.endsWith('-live') ? 'live model' : 'simulated, offline');
    const rows = r.headlines.filter((h, i) => i < 2 || h.negative);
    for (const h of rows) {
      const label = h.negative ? `${h.label} (negative result)` : h.label;
      lines.push(`| ${cell(label)} | ${cell(h.value)} | ${cell(h.baseline)} | ${how} · \`${cell(r.suite)}\` |`);
    }
  }
  return lines.join('\n');
}

const START = '<!-- numbers:start -->';
const END = '<!-- numbers:end -->';

function main(): void {
  const results = readResults();
  const target = path.join(EVALS_DIR, 'RESULTS.md');
  writeFileSync(target, renderReport(results));
  const readme = path.join(EVALS_DIR, '..', 'README.md');
  if (existsSync(readme)) {
    const text = readFileSync(readme, 'utf8');
    const a = text.indexOf(START);
    const b = text.indexOf(END);
    if (a !== -1 && b > a) writeFileSync(readme, `${text.slice(0, a + START.length)}\n${renderReadmeNumbers(results)}\n${text.slice(b)}`);
  }
  console.log(`report: ${results.length} suites -> ${path.relative(process.cwd(), target) || target}`);
}

// Writes files only when run as a script, so the renderers can be tested.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
