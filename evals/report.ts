/**
 * Regenerates evals/RESULTS.md from every evals/results/*.json. Nothing in RESULTS.md is typed by
 * hand: run `pnpm evals:all` (all suites, then this) or `pnpm evals:report` (this only).
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { EVALS_DIR, readResults, scriptPath, type SuiteResult } from './lib/results';

const cell = (s: string | number | undefined) => (s === undefined || s === '' ? '—' : String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '));

function suiteSection(r: SuiteResult): string {
  const out: string[] = [];
  out.push(`## ${r.title}`);
  out.push('');
  out.push(`Suite \`${r.suite}\` · ran ${r.ranAt} · git ${r.gitSha}`);
  out.push('');
  out.push('| Result | Value | Baseline | Interval | n | Script |');
  out.push('| --- | --- | --- | --- | --- | --- |');
  for (const h of r.headlines) {
    const label = h.negative ? `${h.label} **(negative result)**` : h.label;
    out.push(`| ${cell(label)} | ${cell(h.value)} | ${cell(h.baseline)} | ${cell(h.interval)} | ${cell(h.n)} | \`${cell(h.script)}\` |`);
  }
  const notes = r.headlines.filter((h) => h.note);
  if (notes.length > 0) {
    out.push('');
    out.push('Notes:');
    out.push('');
    for (const h of notes) out.push(`- ${h.label}: ${h.note}`);
  }
  if (r.limitations && r.limitations.length > 0) {
    out.push('');
    out.push('Limitations:');
    out.push('');
    for (const l of r.limitations) out.push(`- ${l}`);
  }
  out.push('');
  out.push(`Full per-item data: \`evals/results/${r.suite}.json\` (\`details\`).`);
  return out.join('\n');
}

export function renderReport(results: SuiteResult[]): string {
  const lines: string[] = [];
  lines.push('# Evaluation results');
  lines.push('');
  lines.push(
    `Generated by \`${scriptPath(import.meta.url)}\` from \`evals/results/*.json\`. Every number below was written by the script named next to it. Do not edit this file by hand; run \`pnpm evals:all\`.`,
  );
  lines.push('');
  lines.push('Anything simulated says so in its row or its limitations. No suite here ran against the PayPal sandbox ledger or a live model.');
  lines.push('');
  if (results.length === 0) {
    lines.push('No result files yet.');
    return `${lines.join('\n')}\n`;
  }
  lines.push('| Suite | Results | Negative results | Ran at (UTC) | Git |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const r of results) {
    lines.push(`| ${cell(r.title)} | ${r.headlines.length} | ${r.headlines.filter((h) => h.negative).length} | ${cell(r.ranAt)} | ${cell(r.gitSha)} |`);
  }
  lines.push('');
  for (const r of results) {
    lines.push(suiteSection(r));
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const results = readResults();
const target = path.join(EVALS_DIR, 'RESULTS.md');
writeFileSync(target, renderReport(results));
console.log(`report: ${results.length} suites -> ${path.relative(process.cwd(), target) || target}`);
